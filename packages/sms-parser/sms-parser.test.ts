function runTestSuite(): void {
  console.log(`Running MedVeda SMS Parser Test Suite (${TEST_CASES.length} labelled cases)...`);
  assert.ok(
    TEST_CASES.length >= 105,
    `Expected at least 105 test cases, got ${TEST_CASES.length}`
  );

  // Verify exports
  assert.equal(Object.keys(KNOWN_FACILITIES).length, 5, 'Should export 5 known facilities');
  assert.equal(Object.keys(KNOWN_DEPARTMENTS).length, 8, 'Should export 8 known departments');
  const helpText = getSmsGrammarHelpText();
  assert.ok(helpText.length > 20 && helpText.length <= 160, 'Help text must fit in 160 GSM-7 chars');

  let passed = 0;

  for (const tc of TEST_CASES) {
    const result = parseInboundSms({
      messageId: `msg_${tc.id}`,
      msisdn: '+919876543210',
      text: tc.text,
      receivedAt: tc.receivedAt ?? MORNING_REF,
    });

    try {
      // 1. Verify envelope metadata
      assert.equal(result.messageId, `msg_${tc.id}`);
      assert.equal(result.msisdn, '+919876543210');
      assert.equal(result.receivedAt, tc.receivedAt ?? MORNING_REF);

      // 2. Verify exact JSON keys on result and result.entities
      assert.deepEqual(Object.keys(result), [
        'messageId',
        'msisdn',
        'receivedAt',
        'intent',
        'entities',
        'confidence',
        'parseErrors',
      ]);
      assert.deepEqual(Object.keys(result.entities), [
        'facilityCode',
        'deptCode',
        'requestedDate',
        'session',
        'confirmCode',
        'trackingId',
      ]);

      // 3. Verify intent
      assert.equal(
        result.intent,
        tc.expectedIntent,
        `[${tc.id}] Expected intent ${tc.expectedIntent}, got ${result.intent}`
      );

      // 4. Verify entities if specified
      if (tc.expectedFacility !== undefined) {
        assert.equal(
          result.entities.facilityCode,
          tc.expectedFacility,
          `[${tc.id}] Facility mismatch`
        );
      }
      if (tc.expectedDept !== undefined) {
        assert.equal(result.entities.deptCode, tc.expectedDept, `[${tc.id}] Dept mismatch`);
      }
      if (tc.expectedDate !== undefined) {
        assert.equal(
          result.entities.requestedDate,
          tc.expectedDate,
          `[${tc.id}] Date mismatch`
        );
        // Also check non-enumerable .date getter compatibility
        assert.equal(result.entities.date, tc.expectedDate);
      }
      if (tc.expectedSession !== undefined) {
        assert.equal(
          result.entities.session,
          tc.expectedSession,
          `[${tc.id}] Session mismatch`
        );
      }
      if (tc.expectedConfirmCode !== undefined) {
        assert.equal(
          result.entities.confirmCode,
          tc.expectedConfirmCode,
          `[${tc.id}] ConfirmCode mismatch`
        );
      }
      if (tc.expectedTrackingId !== undefined) {
        assert.equal(
          result.entities.trackingId,
          tc.expectedTrackingId,
          `[${tc.id}] TrackingId mismatch`
        );
      }

      // 5. Verify confidence bounds
      if (tc.minConfidence !== undefined) {
        assert.ok(
          result.confidence >= tc.minConfidence,
          `[${tc.id}] Expected confidence >= ${tc.minConfidence}, got ${result.confidence}`
        );
      }
      if (tc.maxConfidence !== undefined) {
        assert.ok(
          result.confidence <= tc.maxConfidence,
          `[${tc.id}] Expected confidence <= ${tc.maxConfidence}, got ${result.confidence}`
        );
      }

      // 6. Verify parseErrors
      if (tc.expectedParseErrors !== undefined) {
        assert.deepEqual(
          result.parseErrors,
          tc.expectedParseErrors,
          `[${tc.id}] parseErrors mismatch`
        );
      }

      // 7. Enforce safety invariant on BOOK intent:
      // Low confidence (< 0.75) or missing required entities NEVER produce a BOOK intent without parseErrors
      if (result.intent === 'BOOK') {
        const missingRequired =
          !result.entities.facilityCode ||
          !result.entities.deptCode ||
          !result.entities.requestedDate;
        if (result.confidence < 0.75 || missingRequired) {
          assert.ok(
            result.parseErrors.length > 0,
            `[${tc.id}] Safety invariant violated: BOOK with low confidence or missing entities has empty parseErrors`
          );
        } else {
          assert.equal(
            result.parseErrors.length,
            0,
            `[${tc.id}] Valid BOOK should have no parseErrors`
          );
        }
      }

      passed++;
    } catch (err) {
      console.error(`FAILED test case ${tc.id} (${tc.description}): input="${tc.text}"`);
      console.error('Result:', JSON.stringify(result, null, 2));
      throw err;
    }
  }

  console.log(`SUCCESS: ${passed}/${TEST_CASES.length} SMS parser test cases passed!`);
}

runTestSuite();
